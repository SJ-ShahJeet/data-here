#!/usr/bin/env python3
"""Merge memory/state.yaml + graph scout + god nodes into memory/.agent-brief.yaml."""

from __future__ import annotations

import importlib.util
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path


def _load_mg_config():
    path = Path(__file__).resolve().parent / "mg_config.py"
    spec = importlib.util.spec_from_file_location("mg_config", path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


mg = _load_mg_config()

_ENGINE = Path(__file__).resolve().parent
if str(_ENGINE) not in sys.path:
    sys.path.insert(0, str(_ENGINE))
from mg_graph import rank


def _load_memory_nodes():
    """Load the memory-nodes store module; None when a sandbox ships without it."""
    try:
        path = _ENGINE / "memory_nodes.py"
        spec = importlib.util.spec_from_file_location("memory_nodes", path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        return mod
    except (ImportError, OSError):
        return None


memory_nodes = _load_memory_nodes()

# The five node kinds memory_nodes.py ever files a claim under.
_KNOWN_KINDS = ("Decision", "Constraint", "Open thread", "Dependency", "Test/CI fact")


def _inject_kinds(cfg: dict) -> list[str] | None:
    """Config's comma list of kinds to inject (case-insensitive); unknown/empty falls back to all."""
    raw = str(cfg.get("inject_kinds", ""))
    by_lower = {k.lower(): k for k in _KNOWN_KINDS}
    kinds = [by_lower[k.strip().lower()] for k in raw.split(",") if k.strip().lower() in by_lower]
    return kinds or None


def _number(cfg: dict, key: str, default: float, cast=float):
    """A numeric config value, or the default when the value is not a number."""
    try:
        return cast(cfg.get(key, default))
    except (TypeError, ValueError):
        return cast(default)


def _forget_injected(mem: Path) -> None:
    # A brief that was not assembled injected nothing; drop the previous run's record.
    try:
        (mem / ".brief-injected.json").unlink()
    except OSError:
        pass


def repo_root() -> Path:
    root = os.environ.get("REPO_ROOT")
    return Path(root) if root else Path.cwd()


def strip_header(text: str) -> str:
    lines = []
    for line in text.splitlines():
        if line.startswith("# Auto-generated"):
            continue
        lines.append(line)
    return "\n".join(lines).strip()


def tail_lines(text: str, max_lines: int) -> str:
    lines = [ln for ln in text.splitlines() if ln.strip()]
    if len(lines) <= max_lines:
        return "\n".join(lines)
    return "\n".join(lines[:max_lines]) + f"\n# ... ({len(lines) - max_lines} lines truncated)"


def read_section(path: Path, max_lines: int) -> str | None:
    if not path.is_file():
        return None
    text = strip_header(path.read_text(encoding="utf-8", errors="replace"))
    if not text:
        return None
    return tail_lines(text, max_lines)


def top_god_nodes(root: Path, limit: int = 5) -> list[str]:
    data = rank.load_graph_json(mg.graph_json(root))
    return [f"`{g['label']}` ({g['edges']} edges)" for g in rank.god_nodes(data, limit=limit)]


def graph_scout_in_brief(cfg: dict) -> bool:
    if not mg.config_bool(cfg, "graph_scout_on_stop"):
        return False
    if not mg.config_bool(cfg, "graph_scout_local"):
        return False
    if mg.config_bool(cfg, "ollama_context_on_start"):
        return False
    return True


def assemble(root: Path) -> tuple[bool, str]:
    cfg = mg.load_config(root)
    if not mg.config_bool(cfg, "agent_brief"):
        _forget_injected(mg.memory_dir(root))
        return False, "agent_brief disabled"

    max_lines = int(cfg.get("agent_brief_max_lines") or 45)
    mem = mg.memory_dir(root)
    mem.mkdir(parents=True, exist_ok=True)

    ts = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    profile = cfg.get("profile", "standard")
    parts = [
        "# Auto-generated by assemble-agent-brief.py — read ONLY this file at task start.",
        f"updated: {ts}",
        f"profile: {profile}",
        "",
        "## Read order",
        "brief (this file) → main.mdc Working On → sessions/ today → archive/ on demand",
        "",
    ]

    gods = top_god_nodes(root)
    if gods:
        parts.extend(["## God nodes", *[f"- {g}" for g in gods], ""])

    state = read_section(mem / "state.yaml", min(18, max_lines))
    scout = None
    if graph_scout_in_brief(cfg):
        scout = read_section(mem / ".graph-scout.yaml", min(20, max_lines))
    tool_brief = read_section(mem / ".tool-brief-last.txt", 10)

    kinds = _inject_kinds(cfg)
    min_weight = _number(cfg, "inject_min_weight", 0.3, float)
    budget = _number(cfg, "inject_budget_tokens", 6000, int)
    chosen: list = []
    if memory_nodes is not None and (mem / "nodes.json").is_file():
        store = memory_nodes.load_store(root)
        chosen = memory_nodes.select(store, kinds=kinds, min_weight=min_weight, budget_tokens=budget)

    if not any([state, scout, tool_brief, gods, bool(chosen)]):
        _forget_injected(mem)
        return False, "nothing to assemble"

    if state:
        parts.extend(["## Working memory", state, ""])
    if chosen:
        parts.extend(["## Memory nodes", *[f"- ({n['kind']}) {n['claim']}" for n in chosen], ""])
    if scout:
        parts.extend(["## Graph scout", scout, ""])
    if tool_brief:
        parts.extend(["## Last large tool output (summary)", tool_brief, ""])

    body = "\n".join(parts).strip() + "\n"
    body = tail_lines(body, max_lines + 10) + "\n"
    # Only nodes whose line survived the line cap count as injected.
    kept_lines = set(body.splitlines())
    chosen = [n for n in chosen if f"- ({n['kind']}) {n['claim']}" in kept_lines]

    out = mem / ".agent-brief.yaml"
    out.write_text(body, encoding="utf-8")

    status = mem / ".agent-brief-status"
    status.write_text(f"ok: true\ndate: {ts}\nlines: {len(body.splitlines())}\n", encoding="utf-8")

    injected = mem / ".brief-injected.json"
    injected.write_text(
        json.dumps({"updated": ts, "ids": [n["id"] for n in chosen]}, indent=2) + "\n",
        encoding="utf-8",
    )
    return True, f"assembled {len(body.splitlines())} lines"


def main() -> int:
    root = repo_root()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        cfg = mg.load_config(root)
        out = mg.memory_dir(root) / ".agent-brief.yaml"
        print(f"agent_brief: {mg.config_bool(cfg, 'agent_brief')}")
        print(f"  profile: {cfg.get('profile')}")
        print(f"  max_lines: {cfg.get('agent_brief_max_lines', 45)}")
        print(f"  file: {'ok' if out.is_file() else 'missing'}")
        return 0 if mg.config_bool(cfg, "agent_brief") else 1

    # A stop hook must never fail the agent's turn: an unexpected error is
    # reported on stderr and the exit code stays the same as "nothing to do".
    try:
        ok, msg = assemble(root)
    except Exception as exc:  # noqa: BLE001 — hook boundary
        print(f"assemble failed: {exc}", file=sys.stderr)
        return 1
    if not ok:
        print(msg, file=sys.stderr)
        return 1
    print(msg)
    return 0


if __name__ == "__main__":
    sys.exit(main())
